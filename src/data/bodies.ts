export default BODIES;

export const TOTAL_BODIES = BODIES.length;

const BY_ID = new Map(BODIES.map((b) => [b.id, b]));

export function bodyById(id: string | undefined): Body | undefined {
  return id ? BY_ID.get(id) : undefined;
}

export function bodiesByZone(zone: Zone): Body[] {
  return BODIES.filter((b) => b.zone === zone && !b.parent && !b.wanderer);
}

export function moonsOf(parentId: string): Body[] {
  return BODIES.filter((b) => b.parent === parentId);
}

/**
 * Objets posés sur un anneau de la carte système (planètes + planètes naines de Kuiper).
 * La ceinture d'astéroïdes est représentée par un anneau + des cailloux décoratifs ;
 * ses corps individuels vivent dans la sous-carte `/zone/ceinture`.
 */
export function mainMapBodies(): Body[] {
  return BODIES.filter(
    (b) => !b.parent && !b.wanderer && b.id !== 'soleil' && b.zone !== 'ceinture',
  );
}

/** Corps de la ceinture d'astéroïdes, pour la sous-carte. */
export function beltBodies(): Body[] {
  return BODIES.filter((b) => b.zone === 'ceinture' && !b.parent);
}

/** Comètes et sondes. */
export function wanderers(): Body[] {
  return BODIES.filter((b) => b.wanderer);
}

const codexSort = (a: Body, b: Body) =>
  a.facts.distanceSunKm - b.facts.distanceSunKm ||
  (a.parent ? 1 : 0) - (b.parent ? 1 : 0) ||
  b.size - a.size;

/** Tous les corps d'une zone (planètes + lunes), ordonnés pour le codex. */
export function bodiesOfZone(zone: Zone): Body[] {
  return BODIES.filter((b) => b.zone === zone && !b.wanderer).sort(codexSort);
}

/** Les 42 objets dans l'ordre canonique (zones puis errants) — pour le mode classe. */
export function codexOrder(): Body[] {
  return [
    ...bodiesOfZone('interne'),
    ...bodiesOfZone('ceinture'),
    ...bodiesOfZone('geantes'),
    ...bodiesOfZone('externe'),
    ...wanderers(),
  ];
}

